"""Validation suite (docs/server-docs/plan.md section 7): replay a frozen historical reference through the
serving path (data_source -> state -> inference) and diff against ground truth captured from the
source `ai-trading-model` repo's actual training-time feature/model code.

The reference fixture (tests/fixtures/validation_reference.npz) is generated by
scripts/generate_validation_fixture.py (run against the source repo) by running
`build_features_and_targets`, `build_sessions`, and the baseline checkpoint directly in the
source repo over two consecutive trading sessions for one ticker (AAPL), including the regime
ETF bars and FRED rows needed to reproduce all 42 feature columns. See docs/server-docs/plan.md section 7 for
the full plan; this script covers steps 1-2 (feature + prediction diff) and step 3 (session
boundary confirmation) using that fixture. Step 4 (MCP tool wrapping) is exercised separately in
server/mcp_server.py's own smoke test.

`validation_reference.npz` key schema (all written by the generation script):
    ticker              str -- the single ticker this fixture covers (currently "AAPL")
    ticker_bars         structured array, `bars` schema (docs/server-docs/data-readme.md) -- raw 1-min bars
                        for `ticker`, spanning 60 min of lookback before session0 through the
                        end of session1
    regime_bars         structured array, `bars` schema -- same window, for the 7 regime ETFs
    fred_rows_json      JSON string of `{date_str: {series_id: value}}` macro rows for every
                        calendar date covered by `ticker_bars`
    sess0_start/_end    int row indices (into the source repo's `features`/`meta` arrays,
                        NOT into `ticker_bars`) bounding trading session 0
    sess0_date          str `YYYY-MM-DD` market-tz calendar date of session 0
    sess1_start/_end/_date  same, for session 1 (the trading day immediately following session 0)
    features_sess0/1    float32 (n_rows, 42) -- source repo's ground-truth feature matrix for
                        each session, computed by `build_features_and_targets`
    preds_sess0/1       float32 (n_rows, 3, 2) -- raw model output (normalized deltas per
                        horizon) from running the checkpoint over each session as one batched
                        GRU call (NOT bar-by-bar -- see PRED_TOL comment below)
    priced_sess0/1      float32 (n_rows, 3, 2) -- preds_sessN denormalized to
                        (peak_price, dip_price) per horizon
    close_sess0/1       float32 (n_rows,) -- `close[t]` used for denormalization
    vol_sess0/1         float32 (n_rows,) -- `realized_vol_15m[t]` used for denormalization
    horizons            int array, e.g. [5, 10, 15]

Regenerate with (must run under the SOURCE repo's interpreter/venv, CWD = source repo root):
    cd /home/jagan/projects/ai-systems/ai-trading-model
    .venv/bin/python /home/jagan/projects/ai-systems/ai-trading-model-deployment/scripts/generate_validation_fixture.py

Usage:
    python -m server.validate_against_eval
Exits non-zero (after printing every failing check) if anything exceeds tolerance.

Coverage limitations (not yet addressed -- see docs/server-docs/plan.md section 7 for the full list):
one ticker (AAPL) / two sessions / ~1,642 bars only; baseline checkpoint only (normalized
checkpoint not run through this fixture-diff, only smoke-tested separately); only the regime
ETFs/macro values that happened to apply to this one historical slice (no missing-data/
stale-macro edge cases exercised); no adversarial/malformed-input testing at the MCP tool
boundary.
"""
from __future__ import annotations

import json
import sys

import numpy as np

from .data_source import get_features_for_ticker
from .sessions import build_sessions
from .config import ModelConfig
from .inference import InferenceEngine
from .state import HiddenStateManager

FIXTURE_PATH = "tests/fixtures/validation_reference.npz"
FEATURE_TOL = 1e-5
# Looser than FEATURE_TOL: the reference ran each session as one batched GRU call (chunk_len=N),
# while serving steps one bar at a time (chunk_len=1 per call, hidden carried across calls).
# Confirmed via an isolated same-weights/same-inputs check that this alone produces ~1e-4 max
# diff in raw preds (differing matmul/cuDNN reduction order for different sequence lengths) --
# not a serving-path bug. Denormalized price tolerance stays tight since this noise washes out.
PRED_TOL = 2e-4
PRICE_TOL = 1e-3  # looser than feature tol: denormalization chains a few float32 ops


def _records_to_dicts(records: np.ndarray) -> list[dict]:
    return [
        {name: (val.item() if hasattr(val, "item") else val) for name, val in zip(records.dtype.names, row)}
        for row in records
    ]


def main() -> int:
    data = np.load(FIXTURE_PATH, allow_pickle=True)
    ticker = str(data["ticker"])
    ticker_bars = _records_to_dicts(data["ticker_bars"])
    regime_bars = _records_to_dicts(data["regime_bars"])
    fred_rows = json.loads(str(data["fred_rows_json"]))
    horizons = data["horizons"].tolist()

    failures: list[str] = []

    # --- Step 1-2: feature vector diff ---
    meta, features = get_features_for_ticker(ticker_bars, regime_bars, fred_rows)
    meta = meta[meta["ticker"] == ticker].reset_index(drop=True)
    features = features[: len(meta)]

    sessions = build_sessions(meta)
    sess0_date, sess1_date = str(data["sess0_date"]), str(data["sess1_date"])
    session_by_date = {s.session_date: s for s in sessions}
    if sess0_date not in session_by_date or sess1_date not in session_by_date:
        failures.append(f"expected session dates {sess0_date!r}/{sess1_date!r} not found in rebuilt sessions")
        print("\n".join(failures))
        return 1
    sess0, sess1 = session_by_date[sess0_date], session_by_date[sess1_date]

    feats0 = features[sess0.start_idx : sess0.end_idx]
    feats1 = features[sess1.start_idx : sess1.end_idx]
    ref_feats0, ref_feats1 = data["features_sess0"], data["features_sess1"]

    for label, actual, ref in (("session0", feats0, ref_feats0), ("session1", feats1, ref_feats1)):
        if actual.shape != ref.shape:
            failures.append(f"[{label}] feature shape mismatch: {actual.shape} vs reference {ref.shape}")
            continue
        max_diff = np.max(np.abs(actual - ref))
        if max_diff > FEATURE_TOL:
            bad_cols = np.where(np.any(np.abs(actual - ref) > FEATURE_TOL, axis=0))[0]
            failures.append(f"[{label}] feature diff {max_diff:.3e} > {FEATURE_TOL:.0e} in columns {bad_cols.tolist()}")
        else:
            print(f"[{label}] feature vectors match reference (max diff {max_diff:.2e})")

    # --- Step 3: session boundary / hidden-state reset confirmation ---
    cfg = ModelConfig(horizons=horizons)
    engine = InferenceEngine("checkpoints/best_model.pt", cfg, n_features=42, normalized=False)
    state_mgr = HiddenStateManager(engine.model)

    priced_all = {0: [], 1: []}
    preds_all = {0: [], 1: []}
    for sess_idx, sess in enumerate((sess0, sess1)):
        for row_idx in range(sess.start_idx, sess.end_idx):
            row_features = features[row_idx : row_idx + 1]
            ts = int(meta["timestamp"].iloc[row_idx])
            with state_mgr.step(ticker, ts) as handle:
                if row_idx == sess.start_idx:
                    if not np.all(handle.hidden.numpy() == 0):
                        failures.append(f"[session{sess_idx}] expected zeroed hidden state at session start, row {row_idx}")
                preds, next_hidden = engine.forward(row_features, handle.hidden)
                handle.commit(next_hidden)
            close = float(meta["close"].iloc[row_idx])
            vol = float(meta["realized_vol_15m"].iloc[row_idx])
            priced = engine.denormalize(preds[-1], close=close, realized_vol_15m=vol)
            priced_all[sess_idx].append([[p.peak_price, p.dip_price] for p in priced])
            preds_all[sess_idx].append(preds[-1].numpy())

    for sess_idx, ref_priced_key, ref_preds_key in (
        (0, "priced_sess0", "preds_sess0"),
        (1, "priced_sess1", "preds_sess1"),
    ):
        actual_preds = np.stack(preds_all[sess_idx])
        ref_preds = data[ref_preds_key]
        max_diff = np.max(np.abs(actual_preds - ref_preds))
        if max_diff > PRED_TOL:
            failures.append(f"[session{sess_idx}] raw preds diff {max_diff:.3e} > {PRED_TOL:.0e}")
        else:
            print(f"[session{sess_idx}] raw preds match reference (max diff {max_diff:.2e})")

        actual_priced = np.stack(priced_all[sess_idx])
        ref_priced = data[ref_priced_key]
        max_diff = np.max(np.abs(actual_priced - ref_priced))
        if max_diff > PRICE_TOL:
            failures.append(f"[session{sess_idx}] denormalized price diff {max_diff:.3e} > {PRICE_TOL:.0e}")
        else:
            print(f"[session{sess_idx}] denormalized (peak_price, dip_price) match reference (max diff {max_diff:.2e})")

    if failures:
        print("\nFAILURES:")
        for f in failures:
            print(f" - {f}")
        return 1

    print("\nAll validation checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
